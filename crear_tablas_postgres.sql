BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Control de migraciones y tipos de contenido de Django
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "django_migrations" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "app" varchar(255) NOT NULL,
    "name" varchar(255) NOT NULL,
    "applied" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "django_content_type" (
    "id" integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "app_label" varchar(100) NOT NULL,
    "model" varchar(100) NOT NULL,
    CONSTRAINT "django_content_type_app_label_model_76bd3d3b_uniq" UNIQUE ("app_label", "model")
);

-- -----------------------------------------------------------------------------
-- 2. Permisos y grupos base de Django (auth)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "auth_permission" (
    "id" integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "name" varchar(255) NOT NULL,
    "content_type_id" integer NOT NULL REFERENCES "django_content_type" ("id") DEFERRABLE INITIALLY DEFERRED,
    "codename" varchar(100) NOT NULL,
    CONSTRAINT "auth_permission_content_type_id_codename_01ab375a_uniq" UNIQUE ("content_type_id", "codename")
);
CREATE INDEX IF NOT EXISTS "auth_permission_content_type_id_2f476e4b" ON "auth_permission" ("content_type_id");

CREATE TABLE IF NOT EXISTS "auth_group" (
    "id" integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "name" varchar(150) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS "auth_group_permissions" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "group_id" integer NOT NULL REFERENCES "auth_group" ("id") DEFERRABLE INITIALLY DEFERRED,
    "permission_id" integer NOT NULL REFERENCES "auth_permission" ("id") DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT "auth_group_permissions_group_id_permission_id_0cd325b0_uniq" UNIQUE ("group_id", "permission_id")
);
CREATE INDEX IF NOT EXISTS "auth_group_permissions_group_id_b120cbf9" ON "auth_group_permissions" ("group_id");
CREATE INDEX IF NOT EXISTS "auth_group_permissions_permission_id_84c5c92e" ON "auth_group_permissions" ("permission_id");

-- -----------------------------------------------------------------------------
-- 3. Módulo de Autenticación: Login y Registro (HU-01, HU-02, HU-03, HU-04)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "cuentas_usuario" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "password" varchar(128) NOT NULL,
    "last_login" timestamp with time zone NULL,
    "is_superuser" boolean NOT NULL DEFAULT false,
    "nombre" varchar(150) NOT NULL,
    "email" varchar(254) NOT NULL UNIQUE,
    "is_active" boolean NOT NULL DEFAULT true,
    "is_staff" boolean NOT NULL DEFAULT false,
    "fecha_registro" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS "usuario_email_unico_ci" ON "cuentas_usuario" ((LOWER("email")));

CREATE TABLE IF NOT EXISTS "cuentas_usuario_groups" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "usuario_id" bigint NOT NULL REFERENCES "cuentas_usuario" ("id") DEFERRABLE INITIALLY DEFERRED,
    "group_id" integer NOT NULL REFERENCES "auth_group" ("id") DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT "cuentas_usuario_groups_usuario_id_group_id_f5ef6c73_uniq" UNIQUE ("usuario_id", "group_id")
);
CREATE INDEX IF NOT EXISTS "cuentas_usuario_groups_usuario_id_251ff583" ON "cuentas_usuario_groups" ("usuario_id");
CREATE INDEX IF NOT EXISTS "cuentas_usuario_groups_group_id_e6725cc8" ON "cuentas_usuario_groups" ("group_id");

CREATE TABLE IF NOT EXISTS "cuentas_usuario_user_permissions" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "usuario_id" bigint NOT NULL REFERENCES "cuentas_usuario" ("id") DEFERRABLE INITIALLY DEFERRED,
    "permission_id" integer NOT NULL REFERENCES "auth_permission" ("id") DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT "cuentas_usuario_user_per_usuario_id_permission_id_26c0acea_uniq" UNIQUE ("usuario_id", "permission_id")
);
CREATE INDEX IF NOT EXISTS "cuentas_usuario_user_permissions_usuario_id_5a9718f1" ON "cuentas_usuario_user_permissions" ("usuario_id");
CREATE INDEX IF NOT EXISTS "cuentas_usuario_user_permissions_permission_id_1753ad79" ON "cuentas_usuario_user_permissions" ("permission_id");

-- -----------------------------------------------------------------------------
-- 4. Control de Intentos Fallidos de Autenticación (HU-05 — Sprint 2)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "cuentas_intentoacceso" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "email" varchar(254) NOT NULL,
    "ip_address" inet NOT NULL,
    "intentos_fallidos" smallint NOT NULL DEFAULT 0 CHECK ("intentos_fallidos" >= 0),
    "primer_intento_en" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "ultimo_intento_en" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "bloqueado_hasta" timestamp with time zone NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS "intento_email_ip_unico_ci" ON "cuentas_intentoacceso" ((LOWER("email")), "ip_address");

-- -----------------------------------------------------------------------------
-- 5. Sesiones y bitácora del panel de administración de Django
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "django_admin_log" (
    "id" integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "action_time" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "object_id" text NULL,
    "object_repr" varchar(200) NOT NULL,
    "action_flag" smallint NOT NULL CHECK ("action_flag" >= 0),
    "change_message" text NOT NULL,
    "content_type_id" integer NULL REFERENCES "django_content_type" ("id") DEFERRABLE INITIALLY DEFERRED,
    "user_id" bigint NOT NULL REFERENCES "cuentas_usuario" ("id") DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX IF NOT EXISTS "django_admin_log_content_type_id_c4bce8eb" ON "django_admin_log" ("content_type_id");
CREATE INDEX IF NOT EXISTS "django_admin_log_user_id_c564eba6" ON "django_admin_log" ("user_id");

CREATE TABLE IF NOT EXISTS "django_session" (
    "session_key" varchar(40) NOT NULL PRIMARY KEY,
    "session_data" text NOT NULL,
    "expire_date" timestamp with time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS "django_session_expire_date_a5c62663" ON "django_session" ("expire_date");

-- -----------------------------------------------------------------------------
-- 6. NUEVA TABLA SPRINT 3: Organizador de Tareas y Calendario (`tareas_tarea`)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "tareas_tarea" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "nombre" varchar(150) NOT NULL,
    "descripcion" text NOT NULL DEFAULT '',
    "fecha_inicio" date NOT NULL,
    "fecha_fin" date NOT NULL,
    "estado" varchar(20) NOT NULL DEFAULT 'Pendiente',
    "creado_en" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "actualizado_en" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "usuario_id" bigint NOT NULL REFERENCES "cuentas_usuario" ("id") ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT "tarea_fecha_fin_mayor_igual_inicio" CHECK ("fecha_fin" >= ("fecha_inicio")),
    CONSTRAINT "tarea_estado_valido" CHECK ("estado" IN ('Pendiente', 'En progreso', 'Completada'))
);
CREATE INDEX IF NOT EXISTS "tareas_tarea_usuario_id_02eab1d8" ON "tareas_tarea" ("usuario_id");

