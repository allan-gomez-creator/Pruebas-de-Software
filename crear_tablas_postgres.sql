-- SCRIPT COMPLETO POSTGRESQL — PRUEBAS DE SOFTWARE (Sprints 1, 2 y 3)
-- Base de datos: pruebas
-- =============================================================================
-- Este script es seguro (usa IF NOT EXISTS):
--   1. Si la base de datos `pruebas` está vacía, crea todas las tablas de
--      Django, Login/Registro (`cuentas_usuario`), Intentos fallidos
--      (`cuentas_intentoacceso`) y Sprint 3 (`tareas_tarea`).
--   2. Si ya tenías creadas las tablas de Login en `pruebas`, conserva tus
--      tablas y datos actuales y añade las tablas nuevas que falten (`tareas_tarea`).
